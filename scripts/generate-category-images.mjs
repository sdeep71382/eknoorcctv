import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = resolve(projectRoot, "app/downloads/images.csv");
const outputPath = resolve(projectRoot, "lib/generated/category-images.ts");
const rasterExtensions = new Set([".avif", ".jpeg", ".jpg", ".png", ".webp"]);

function parseCsvLine(line) {
  const fields = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < line.length; index += 1) {
    const character = line[index];
    if (character === '"' && quoted && line[index + 1] === '"') {
      field += '"';
      index += 1;
    } else if (character === '"') {
      quoted = !quoted;
    } else if (character === "," && !quoted) {
      fields.push(field);
      field = "";
    } else {
      field += character;
    }
  }

  fields.push(field);
  return fields;
}

function categoryAlt(category, index) {
  const label = category.replaceAll("-", " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
  if (category === "about-us") {
    return index === 0 ? "Eknoor CCTV security service commitment" : "Eknoor CCTV security service mission";
  }
  if (category === "homepage") {
    return index === 0 ? "Integrated CCTV and security solution" : "Professional security system installation";
  }
  return index === 0 ? `${label} security solution` : `${label} installation and equipment`;
}

if (!existsSync(csvPath)) {
  throw new Error(`Image manifest not found: ${csvPath}`);
}

const [headerLine, ...lines] = readFileSync(csvPath, "utf8").replace(/^\uFEFF/, "").split(/\r?\n/).filter(Boolean);
const headers = parseCsvLine(headerLine);
const rows = lines.map((line) => Object.fromEntries(headers.map((header, index) => [header, parseCsvLine(line)[index] ?? ""])));
const grouped = new Map();

for (const row of rows) {
  const localFile = row["Local File"];
  const category = row.Category;
  if (!localFile || !category) continue;

  const absolutePath = resolve(projectRoot, "app/downloads", localFile.replace(/[\\/]/g, sep));
  if (!existsSync(absolutePath) || !rasterExtensions.has(extname(absolutePath).toLowerCase())) continue;

  const candidate = {
    absolutePath,
    size: statSync(absolutePath).size,
    title: row.Title.toLowerCase(),
  };
  const candidates = grouped.get(category) ?? [];
  candidates.push(candidate);
  grouped.set(category, candidates);
}

const selected = [...grouped.entries()].map(([category, candidates]) => {
  const preferred = candidates.filter(({ size, title }) => size >= 40_000 && !/(logo|whatsapp)/.test(title));
  return [category, (preferred.length ? preferred : candidates).slice(0, 2)];
});

const imports = [];
const manifestEntries = [];
let importIndex = 0;

for (const [category, images] of selected) {
  const assets = images.map(({ absolutePath }, imageIndex) => {
    const importName = `categoryImage${importIndex}`;
    importIndex += 1;
    const importPath = relative(dirname(outputPath), absolutePath).split(sep).join("/");
    imports.push(`import ${importName} from ${JSON.stringify(importPath.startsWith(".") ? importPath : `./${importPath}`)};`);
    return `    { src: ${importName}, alt: ${JSON.stringify(categoryAlt(category, imageIndex))} },`;
  });

  manifestEntries.push(`  ${JSON.stringify(category)}: [\n${assets.join("\n")}\n  ],`);
}

const output = `/* This file is generated by scripts/generate-category-images.mjs. */
import type { StaticImageData } from "next/image";
${imports.join("\n")}

export type CategoryImageAsset = { src: StaticImageData; alt: string };

export const categoryImages: Record<string, CategoryImageAsset[]> = {
${manifestEntries.join("\n")}
};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
console.log(`Generated ${selected.length} category mappings at ${relative(projectRoot, outputPath)}.`);

